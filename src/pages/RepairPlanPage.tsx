import React, { useState, useEffect } from 'react';
import {
  Wrench,
  ArrowLeft,
  CheckCircle2,
  AlertTriangle,
  Play,
  FileCode,
  ShieldCheck,
  Cpu,
  RefreshCw
} from 'lucide-react';
import { api } from '../services/api';
import { RepairPlan } from '../../shared/types';

interface RepairPlanPageProps {
  planId: string;
  onNavigate: (page: string, params?: any) => void;
}

export const RepairPlanPage: React.FC<RepairPlanPageProps> = ({ planId, onNavigate }) => {
  const [plan, setPlan] = useState<RepairPlan | null>(null);
  const [loading, setLoading] = useState(true);
  const [executing, setExecuting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const fetchPlan = async () => {
      try {
        setLoading(true);
        const data = await api.getRepairPlan(planId);
        setPlan(data);
      } catch (e: any) {
        setError(e.message);
      } finally {
        setLoading(false);
      }
    };
    fetchPlan();
  }, [planId]);

  const handleApproveAndExecute = async () => {
    try {
      setExecuting(true);
      setError(null);
      const res = await api.executeRepairPlan(planId);
      onNavigate('agent-run-detail', { runId: res.run_id });
    } catch (e: any) {
      setError(e.message || 'Failed to start execution');
      setExecuting(false);
    }
  };

  if (loading || !plan) {
    return (
      <div className="p-8 text-center text-xs text-zinc-500 font-mono">
        <RefreshCw className="w-5 h-5 animate-spin mx-auto mb-2 text-zinc-600" />
        Loading repair strategy...
      </div>
    );
  }

  return (
    <div className="p-6 max-w-4xl mx-auto space-y-6">
      {/* Back button */}
      <button
        onClick={() => onNavigate('issues')}
        className="flex items-center gap-1.5 text-xs text-zinc-400 hover:text-zinc-200 transition-colors"
      >
        <ArrowLeft className="w-3.5 h-3.5" />
        <span>Back to Issues</span>
      </button>

      {/* Plan Header */}
      <div className="p-6 rounded-xl border border-zinc-800 bg-zinc-900/30 space-y-5">
        <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4">
          <div className="space-y-1">
            <div className="flex items-center gap-2">
              <Wrench className="w-5 h-5 text-emerald-400" />
              <h1 className="text-xl font-bold text-zinc-100">{plan.title}</h1>
            </div>
            <p className="text-xs text-zinc-400">
              Generated by Repair Planner Agent · Requires explicit human approval to execute
            </p>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => onNavigate('issues')}
              className="px-3 py-1.5 rounded text-xs text-zinc-400 hover:text-zinc-200 hover:bg-zinc-800 transition-colors"
            >
              Cancel
            </button>
            <button
              onClick={handleApproveAndExecute}
              disabled={executing}
              className="flex items-center gap-2 px-5 py-2.5 rounded bg-emerald-500 hover:bg-emerald-400 text-zinc-950 text-xs font-bold transition-colors disabled:opacity-50 cursor-pointer shadow-lg shadow-emerald-500/10"
            >
              <Play className="w-3.5 h-3.5 fill-current" />
              <span>{executing ? 'Starting Isolated Run...' : 'Approve & Execute'}</span>
            </button>
          </div>
        </div>

        {error && (
          <div className="p-3 rounded bg-rose-950/40 border border-rose-800 text-xs text-rose-300">
            {error}
          </div>
        )}

        {/* Structured Decision Summary */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-xs font-mono">
          <div className="p-3.5 rounded bg-zinc-950 border border-zinc-800 space-y-1">
            <span className="text-zinc-500 uppercase text-[10px]">Problem</span>
            <p className="text-zinc-200 text-xs font-sans leading-relaxed">{plan.problem}</p>
          </div>

          <div className="p-3.5 rounded bg-zinc-950 border border-zinc-800 space-y-1">
            <span className="text-zinc-500 uppercase text-[10px]">Root Cause</span>
            <p className="text-zinc-200 text-xs font-sans leading-relaxed">{plan.root_cause}</p>
          </div>
        </div>

        {/* Proposed Fix */}
        <div className="p-3.5 rounded bg-emerald-950/20 border border-emerald-800/30 text-xs space-y-1">
          <span className="font-mono text-emerald-400 uppercase text-[10px]">Proposed Fix</span>
          <p className="text-emerald-200 leading-relaxed font-sans">{plan.proposed_fix}</p>
        </div>

        {/* Key Constraints: Files & Validation */}
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 text-xs font-mono">
          <div className="p-3 rounded bg-zinc-950 border border-zinc-800 space-y-1">
            <span className="text-zinc-500 uppercase text-[10px]">Files Affected</span>
            <div className="text-zinc-200 font-semibold">{plan.files_affected.length} files</div>
            <div className="text-zinc-400 text-[11px] truncate">{plan.files_affected.join(', ')}</div>
          </div>

          <div className="p-3 rounded bg-zinc-950 border border-zinc-800 space-y-1">
            <span className="text-zinc-500 uppercase text-[10px]">Validation Suite</span>
            <div className="text-zinc-200 font-semibold">{plan.validation_commands.length} checks</div>
            <div className="text-zinc-400 text-[11px]">{plan.validation_commands.join(' && ')}</div>
          </div>

          <div className="p-3 rounded bg-zinc-950 border border-zinc-800 space-y-1">
            <span className="text-zinc-500 uppercase text-[10px]">Risk Assessment</span>
            <div
              className={`font-bold uppercase ${
                plan.risk_level === 'low'
                  ? 'text-emerald-400'
                  : plan.risk_level === 'medium'
                  ? 'text-amber-400'
                  : 'text-rose-400'
              }`}
            >
              {plan.risk_level} Risk
            </div>
            <div className="text-zinc-400 text-[11px]">Surgical targeted patch</div>
          </div>
        </div>

        {/* Step-by-Step Action Sequence */}
        <div className="space-y-3 pt-2">
          <h3 className="text-xs font-mono uppercase text-zinc-400">Planned Execution Steps</h3>
          <div className="space-y-2">
            {plan.steps && plan.steps.map((st, idx) => (
              <div
                key={idx}
                className="flex items-start gap-3 p-3 rounded bg-zinc-950 border border-zinc-800 text-xs"
              >
                <div className="w-5 h-5 rounded bg-zinc-800 text-zinc-300 font-mono flex items-center justify-center text-[11px] shrink-0 font-bold">
                  {st.step_number || idx + 1}
                </div>
                <div className="space-y-0.5">
                  <div className="font-semibold text-zinc-200 flex items-center gap-2">
                    <span>{st.action}</span>
                    {st.target_file && (
                      <span className="text-zinc-500 font-mono text-[11px]">({st.target_file})</span>
                    )}
                  </div>
                  <p className="text-zinc-400 text-[11px] leading-relaxed">{st.description}</p>
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
};
